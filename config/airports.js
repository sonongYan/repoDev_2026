// 把词典渲染为可拼进系统提示词的文本（每行「三字码=中文全称」）
function renderAirportGlossary() {
  return Object.entries(AIRPORT_CODES)
    .map(([code, name]) => `${code}=${name}`)
    .join('，');
}

function getAirportName(code) {
  if (!code) return null;
  return AIRPORT_CODES[String(code).toUpperCase()] || null;
}

